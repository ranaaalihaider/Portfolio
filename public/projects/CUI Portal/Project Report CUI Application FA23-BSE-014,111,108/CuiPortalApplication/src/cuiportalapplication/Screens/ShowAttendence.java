    public void showOneStudentAttendence(){
        
        Student s=CommonCodes.globalStudentObject;
        lblName.setVisible(true);
        lblName.setText("Name : "+s.getName());
        ArrayList<Attendence> allDaysAttendence=s.getAttendenceOfAllDays();
        model.setColumnIdentifiers(new String[]{"ID","Topic","Date","Status"});
        if(allDaysAttendence==null){
            lblStatus.setText("No Attendence Marked");
        }else{
             SimpleDateFormat dateFormat = new SimpleDateFormat("yyyy-MM-dd");
            String id=s.getId();
            String topic;
            String status;
            String date;
            int present=0;
            for(Attendence oneDay:allDaysAttendence){
                date=dateFormat.format(oneDay.getDate());
                status=oneDay.getStatus();
                topic=oneDay.getTopic();
                if(status.equalsIgnoreCase("Present")){
                    present++;
                }
                model.addRow(new String[]{id,topic,date,status});
            }
            formattedValue = String.format("%.4g", s.getAttendencePercentage());
            lblStatus.setText("Total Classes "+allDaysAttendence.size()+"  Present : "+present +" Percentage "+formattedValue);
            
            
            
        }
       
    }

