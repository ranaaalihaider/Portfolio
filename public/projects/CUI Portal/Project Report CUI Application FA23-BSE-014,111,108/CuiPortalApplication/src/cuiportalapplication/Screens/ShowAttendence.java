    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        model.setRowCount(0);
        String sem=(String)comboSem.getSelectedItem();
        ArrayList<Student> allData=new ArrayList<>();
        allData=FileHandling.readCompleteFile(Student.class);
        for(Student s1:allData){
            if(s1.getSemester().equals(sem)){
                formattedValue = String.format("%.4g", s1.getAttendencePercentage());
                model.addRow(new String[]{s1.getId(), s1.getName(), s1.getSemester(), formattedValue+" %"});
            }
            
        }
        
    }//GEN-LAST:event_btnSearchActionPerformed

