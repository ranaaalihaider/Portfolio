    private void radioViewAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_radioViewAllActionPerformed
        // TODO add your handling code here:
        if(radioViewAll.isSelected()){
            model.setRowCount(0);
            txtId.setEnabled(false);
            btnSearch.setEnabled(false);
        }
        if(personRole.equals("student")){
            ArrayList<Student> allData=new ArrayList<>();
            allData=FileHandling.readCompleteFile(Student.class);
            for(Student s1:allData){
                 model.addRow(new String[]{s1.getId(), s1.getName(), s1.getSemester(), s1.getProgram()});
            }
        }
        else{
             ArrayList<Teacher> allData=new ArrayList<>();
            allData=FileHandling.readCompleteFile(Teacher.class);
            for(Teacher t1:allData){
                  model.addRow(new String[]{t1.getId(),t1.getName(),t1.getQualification(),t1.getSubjectToTeach()});
            }
        }
    }//GEN-LAST:event_radioViewAllActionPerformed

