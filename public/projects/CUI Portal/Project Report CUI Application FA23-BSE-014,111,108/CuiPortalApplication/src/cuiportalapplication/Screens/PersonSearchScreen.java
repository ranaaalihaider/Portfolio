    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String id=txtId.getText();
        if(personRole.equals("student")){
            Student s1=FileHandling.findUsersObjectById(Student.class, id);
            if(s1==null){
                lblStatus.setText("No Data Found !");
            }
            else{
               model.addRow(new String[]{s1.getId(), s1.getName(), s1.getSemester(), s1.getProgram()});
            }
        }else{
            Teacher t1=FileHandling.findUsersObjectById(Teacher.class, id);
            if(t1==null){
                lblStatus.setText("No Data Found !");
            }
            else{
                model.addRow(new String[]{t1.getId(),t1.getName(),t1.getQualification(),t1.getSubjectToTeach()});
            }
        }
    }//GEN-LAST:event_btnSearchActionPerformed

