    private void btnNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNextActionPerformed
        // TODO add your handling code here:
        boolean allChecks=true;
        String nameCheck=CommonCodes.checkText(txtName.getText());
        String fatherNameCheck=CommonCodes.checkText(txtFatherName.getText());
        String ageCheck=CommonCodes.checkNumeric(txtAge.getText());
        String cnicChec=CommonCodes.checkCNIC(txtCnic.getText());
        String phoneNoCheck=CommonCodes.checkNumeric(txtCellNo.getText());
        
        if(!nameCheck.equals("true")){
            lblStatus.setText(nameCheck);
        }else if(!fatherNameCheck.equals("true")){
            lblStatus.setText("Father Name : "+fatherNameCheck);
        }else if(!ageCheck.equals("true")){
            lblStatus.setText("Age : "+ageCheck);
        }else if(!cnicChec.equals("true")){
            lblStatus.setText("CNIC : "+cnicChec);
        }else if(!phoneNoCheck.equals("true")){
            lblStatus.setText("Phone No : "+phoneNoCheck);
        }else if(txtCellNo.getText().length()!=11){
            lblStatus.setText("Enter 11 Digit Number");
        }
        else if(txtAddress.getText().length()==0){
            lblStatus.setText("Enter Address Please !");
        }
            else{
            String name=txtName.getText();
            String fatherName=txtFatherName.getText();
            String age=txtAge.getText();
            String gender="male";
            if(radioFemale.isSelected()){
                gender="female";
            }

            String cnic=txtCnic.getText();
            String contactNumber=txtCellNo.getText();
            String address=txtAddress.getText();
                    Person.personData[0]=name;
                    Person.personData[1]=fatherName;
                    Person.personData[2]=age;
                    Person.personData[3]=gender;
                    Person.personData[4]=cnic;
                    Person.personData[5]=contactNumber;
                    Person.personData[6]=address;

                 dispose();
                 if(role.equals("teacher")){
                    PersonEducationInfoScreenInput obj=new PersonEducationInfoScreenInput("teacher",caller);
                    obj.setVisible(true);
                 }else{
                     PersonEducationInfoScreenInput obj=new PersonEducationInfoScreenInput("student",caller);
                    obj.setVisible(true);
                 }
        }
             
             

        
    }//GEN-LAST:event_btnNextActionPerformed

