    public void scaleImage(){
        String path="";
        if(radioMale.isSelected()){
            path="src\\images\\male_student.png";
        }
        else{
            path="src\\images\\female_student.png";
        }
        ImageIcon icon=new ImageIcon(path);
        Image img=icon.getImage();
        Image imageScale=img.getScaledInstance(lblIcon.getWidth(), lblIcon.getHeight(), img.SCALE_SMOOTH);
        ImageIcon imgFinal=new ImageIcon(imageScale);
        lblIcon.setIcon(imgFinal);
        
    }
