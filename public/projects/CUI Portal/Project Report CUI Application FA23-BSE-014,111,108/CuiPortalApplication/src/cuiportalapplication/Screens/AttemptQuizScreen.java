    private void showQuestion(int i){
        oneQuestion=allQuestions.get(i);
        lblQuestion.setText(oneQuestion.getQuestion());
        String [] options=oneQuestion.getOptions();
        lblA.setText(options[0]);
        lblB.setText(options[1]);
        lblC.setText(options[2]);
        lblD.setText(options[3]);
        
    }
