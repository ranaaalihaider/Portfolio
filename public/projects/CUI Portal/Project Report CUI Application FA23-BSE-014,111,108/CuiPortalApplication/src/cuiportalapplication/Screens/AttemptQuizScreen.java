    private void btnStartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStartActionPerformed
        // TODO add your handling code here:
        
        subjectSelectedByUser=comboSubjectSelect.getSelectedItem().toString();
        allQuestions=FileHandling.getQuizQuestionBySubject(subjectSelectedByUser);
        if(allQuestions==null){
            lblStatus.setText("Question Not Found For Subject !");
        }else{
            showQuestion(index);
            index++;
            btnNext.setEnabled(true);
            btnStart.setEnabled(false);
            comboSubjectSelect.setEnabled(false);
        }
    }//GEN-LAST:event_btnStartActionPerformed

    private void btnNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNextActionPerformed
        // TODO add your handling code here:
        String selectedOption;
        
        if(radioA.isSelected()){
            selectedOption="1";
        }else if(radioB.isSelected()){
            selectedOption="2";
        }else if(radioC.isSelected()){
            selectedOption="3";
        }else{
            selectedOption="4";
        }
         if(selectedOption.equals(oneQuestion.getCorrectAnswer())){
             obtainedMarks++;
         }
         if(index<10){
             showQuestion(index);
             index++;
         }
         else{
             btnNext.setEnabled(false);
             lblStatus.setText("Quiz Completed Submit Please !");
             btnSubmit.setEnabled(true);
         }
        
    }//GEN-LAST:event_btnNextActionPerformed

    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:]
        Marks newQuiz=new Marks(obtainedMarks,subjectSelectedByUser);
        CommonCodes.globalStudentObject.setQuizMarks(newQuiz);
        boolean status=FileHandling.updateObject(CommonCodes.globalStudentObject);
        if(status){
            btnSubmit.setEnabled(false);
            lblStatus.setText("Data Saved You Got "+obtainedMarks+ " Marks ot of 10");
        }else{
            lblStatus.setText("Error in Saving Try Again Try Again !");
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

