    private void btnNextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNextActionPerformed
        // TODO add your handling code here:
        String experienceCheck=CommonCodes.checkNumeric(txtExperience.getText());

       
       
       if(experienceCheck.equals("true") &&role.equalsIgnoreCase("teacher")){
           String qualification=comboQualification.getSelectedItem().toString();
           String experience =txtExperience.getText();
           String Subject=comboSubject.getSelectedItem().toString();
           Teacher.newTeacherData[0]=qualification;
           Teacher.newTeacherData[1]=experience;
           Teacher.newTeacherData[2]=Subject;
           dispose();
            LogInCredentialsScreen obj=new LogInCredentialsScreen("teacher",caller);
            obj.setVisible(true);
       }else if(experienceCheck.equals("true") && role.equalsIgnoreCase("student")){
           
            String semester=comboQualification.getSelectedItem().toString();
            String fscMarks=txtExperience.getText();
            String subject=comboSubject.getSelectedItem().toString();
            Student.newStudentData[0]=semester;
            Student.newStudentData[1]=fscMarks;
            Student.newStudentData[2]=subject;
            dispose();
            LogInCredentialsScreen obj=new LogInCredentialsScreen("student",caller);
            obj.setVisible(true);
       }else{
           lblStatus.setText(experienceCheck);
       }
       
    }//GEN-LAST:event_btnNextActionPerformed

    private void btnSetSubjectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSetSubjectActionPerformed
        // TODO add your handling code here:
        List<String> selectedItems = listSubjects.getSelectedValuesList();
        listSubjects.setEnabled(false);
        btnSetSubject.setEnabled(false);
        //Value to Save in object
         String[] selectedArray = selectedItems.toArray(new String[0]);
         Student.selectedSubject=selectedArray;
         //Screen code
         String subjectSelectedToShow=String.join(" - ", selectedArray);
         
         lblSelectedSubjects.setText(subjectSelectedToShow);
         btnNext.setEnabled(true);
         btnReset.setEnabled(false);
         
    }//GEN-LAST:event_btnSetSubjectActionPerformed

