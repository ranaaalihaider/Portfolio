    public void SetLables(){
        btnNext.setEnabled(true);
        if(role.equalsIgnoreCase("student")){
            lblQualification.setText("Semester");
            lblExperience.setText("FSC Marks");
            lblSubject.setText("Program");
            comboQualification.removeAllItems();
            for(int i=1;i<=8;i++){
               comboQualification.addItem(String.valueOf(i));
            }
            comboSubject.removeAllItems();
            comboSubject.addItem("BSE");
            comboSubject.addItem("BCS");
            comboSubject.addItem("BAI");
            comboSubject.addItem("BDS");
            btnNext.setEnabled(false);
        }else{
            jLabel1.hide();
            lblSelectedSubjects.hide();
            listSubjects.hide();
            btnSetSubject.hide();
            jPanel2.hide();
        }
        
    }
    public void scaleImage(){
       
        String path="src\\images\\Education.png";
    
        ImageIcon icon=new ImageIcon(path);
        Image img=icon.getImage();
        Image imageScale=img.getScaledInstance(lblIcon.getWidth(), lblIcon.getHeight(), img.SCALE_SMOOTH);
        ImageIcon imgFinal=new ImageIcon(imageScale);
        lblIcon.setIcon(imgFinal);
        
    }
